// isTextEmoji says r is one of textEmoji.
func isTextEmoji(r rune) bool {
	lo, hi := 0, len(textEmoji)
	for lo < hi {
		m := (lo + hi) / 2
		switch {
		case r < textEmoji[m][0]:
			hi = m
		case r > textEmoji[m][1]:
			lo = m + 1
		default:
			return true
		}
	}
	return false
}
